#!/usr/bin/env python3
"""Builds pages/archive/palm-hill-link.html ("Palm Hill Link Archives") from data/link-issues.json.
Shell copied from pages/archive/community-stories.html (archive look). STYLE-RULES.md R14.
Links stay relative (link/Link-YYYY-MM.pdf); vercel.json redirects them to the hosted PDF (R15/R29, scripts/link_store.py)."""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import style_rules as _SR
from html import escape as e
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FULL = ("January","February","March","April","May","June","July","August","September","October","November","December")
D = json.load(open(f"{R}/data/link-issues.json"))
tpl = open(f"{R}/pages/archive/community-stories.html", encoding="utf-8").read()
head = tpl[:tpl.index('<main class="ph-body">')]
head = re.sub(r"<title>.*?</title>", "<title>Palm Hill Link Archives — Palm Hill Country Club</title>", head)
head = re.sub(r'rel="canonical" href="[^"]*"', 'rel="canonical" href="https://palmhillnews.vercel.app/pages/archive/palm-hill-link.html"', head)
# STYLE-RULES R44 (Steven, Oct 17 11:35 PM + 11:51 PM): the top bar holds exactly one link, 'All Archives →' -- no
# 'Earlier Issues ↓' / 'Story Archives ↓' jump link (and no separator dot) even if the template still carries one.
head = re.sub(r'<a href="#previous"[^>]*>[^<]*</a><span class="ph-sep"[^>]*>·</span>', '', head)
head = head.replace("<!-- Generated by scripts/build_archive.js from archive/archive-items.json. Edit the data, not this file. -->",
                    "<!-- Generated by scripts/build_link_archive.py from data/link-issues.json. Edit the data, not this file. -->")
B = "https://palmhillnews.vercel.app/pages/"
def mname(m): y, mo = m.split("-"); return f"{FULL[int(mo)-1]} {y}"
_BYTES = {i["pdf"]: i["bytes"] for i in D["issues"]}  # R29: PDFs are not in the repo tree; size comes from the data file
def size(p): return f"{_BYTES[p]/1e6:.0f} MB"
cur, rest = D["issues"][0], D["issues"][1:]
def story(it):
    s = it.get("story")
    return f'<span class="ph-dot"> · </span><a href="{B}{s["page"]}">Community Story: {e(s["title"])} →</a>' if s else ""
body = f'''<main class="ph-body">
<h1 class="ph-section">Palm Hill Link Archives</h1>
<nav class="ph-links ph-link-current"><a href="{e(D["current_download"])}">Palm Hill Link Monthly →</a></nav>
<p class="ph-lead">The Palm Hill Link is our park’s monthly magazine. The current issue comes first, then earlier issues, newest first. Each issue opens as a PDF.</p>
<section class="ph-feature" aria-label="Current Issue">
<p class="ph-feature-kicker">Current Issue</p>
<h2 class="ph-feature-title"><a href="link/{cur["pdf"]}">Palm Hill Link — {mname(cur["month"])}</a></h2>
<div class="ph-row-meta">PDF, {size(cur["pdf"])}</div>
<nav class="ph-links"><a href="link/{cur["pdf"]}">Open the {FULL[int(cur["month"][5:])-1]} issue (PDF) →</a><span class="ph-dot"> · </span><a href="{D["current_hub"]}">Palm Hill Link Monthly page →</a>{story(cur)}</nav>
</section>
<h2 class="ph-subhead ph-prev-head" id="previous">Earlier Issues</h2>
'''
for i, it in enumerate(rest):
    body += f'''<h2 class="ph-subhead">{mname(it["month"])}</h2>
<div class="ph-row{' ph-alt' if i % 2 else ''}"><div class="ph-row-line"><a class="ph-row-title" href="link/{it["pdf"]}">Palm Hill Link — {mname(it["month"])} (PDF) →</a></div>
<div class="ph-row-meta">PDF, {size(it["pdf"])}</div>
{('<nav class="ph-links">' + story(it).replace('<span class="ph-dot"> · </span>', '', 1) + '</nav>') if it.get("story") else ''}
</div>
'''
body += '''<p class="ph-source">Source: Palm Hill Link PDFs as published by monthly-media.com for Palm Hill. Issues not listed (April, June, July 2026 and earlier) are not on hand yet.</p>
</main>
</div>
</body>
</html>
'''
# R81 guard: the current monthly issue link (Helpful Webpages' old 'Palm Hill Link Monthly') is the first link under the title
assert (head + body).split('<h1 class="ph-section">', 1)[1].split("<a ", 1)[1].startswith('href="https://monthly-media.com/newsletter_download.php'), "R81: current monthly issue link must lead palm-hill-link.html"
open(f"{R}/pages/archive/palm-hill-link.html", "w", encoding="utf-8").write(_SR.assert_archive_top(head + body, "palm-hill-link.html")); print("wrote pages/archive/palm-hill-link.html")  # R44
