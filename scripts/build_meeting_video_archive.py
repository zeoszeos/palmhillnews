DATA=os.path.join(ROOT,'archive/committee-videos.json')
GROUPS=[  # slug, label, matcher
 ('board','Board of Directors',lambda g:g.startswith('Board')),
 ('buildings-and-grounds','Buildings & Grounds Committee',lambda g:g.startswith('Buildings')),
 ('communications','Communications Committee',lambda g:g.startswith('Communications')),
 ('finance','Finance Committee',lambda g:g.startswith('Finance')),
 ('golf','Golf Committee',lambda g:g.startswith('Golf')),
 ('planning-and-environmental','Planning & Environmental Committee',lambda g:g.startswith('Planning')),
 ('rules-and-regulations','Rules & Regulations Committee',lambda g:g.startswith('Rules')),
 ('real-estate','Real Estate Committee',lambda g:g.startswith('Real Estate')),
 ('special-meetings','Special Meetings & Town Halls',lambda g:g.startswith('Special')),
]
def slug_for(g):
  for s,l,m in GROUPS:
    if m(g): return s
  return 'other'
def check(url):
  if 'drive.google.com' not in url: return None
  try:
    r=urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':'Mozilla/5.0'}),timeout=20); return r.status
  except urllib.error.HTTPError as e: return e.code
  except Exception: return 0
def load(args):
  if '--from-csv' in args:
    rows=list(csv.DictReader(open(args[args.index('--from-csv')+1])))
    url_count=collections.Counter(r['url'] for r in rows)
    out=[]
    for r in rows:
      g=r['group']; note=r['note']
      if note.startswith('DUPLICATE'): note=''
      sub=g.split(':',1)[1].strip() if g.startswith('Special') else ''
      flags=[]
      if url_count[r['url']]>1: flags.append('duplicate')
      if re.search(r'audio only|sound only',note,re.I): flags.append('audio')
      if r['date']=='2025-09-29' and sub.startswith('Sewer'): flags.append('date-typo')
      out.append(dict(date=r['date'],group=slug_for(g),meeting=sub,note=note.strip(' -'),host=r['host'],url=r['url'],
        source=r['source'],flags=flags,http=r['http'],status=r['status']))
    return out
  return json.load(open(DATA))
def status_of(r):
  h=r['host']
  if 'drive.google.com' in h:
    return 'ok' if str(r['http'])=='200' else 'broken'
  if 'sharepoint' in h: return 'signin'
  return 'unverified'
