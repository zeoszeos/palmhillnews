HUB='pages/archive/meeting-videos.html'
def rng(rs):
  ds=sorted(r['date'] for r in rs); f=lambda d:datetime.date.fromisoformat(d).strftime('%b %Y')
  a,b=f(ds[0]),f(ds[-1]); n=len(rs)
  return (a if a==b else f'{a} – {b}')+f', {n} video'+('' if n==1 else 's')
def live_sync(rows):
  # R61: re-pull the live page each run; add every dated video not yet in the data (Drive link checked first).
  import pull_club_videos as P
  live=P.main(); today=datetime.date.today().isoformat(); added=[]; dead=[]
  have={(r['url'],r['date']) for r in rows}
  for i in live['items']:
    if (i['url'],i['date']) in have: continue
    host=urllib.parse.urlparse(i['url']).netloc
    code=check(i['url']); code=code if code is not None else ''
    if code==404: dead.append(i); continue
    same=[r for r in rows if r['group']==i['group'] and r['date']==i['date'] and r.get('link_status')=='broken']
    src=f'Club Committees page (live, pulled {today})'
    if same:  # club replaced a dead file with a new link for the same meeting
      r=same[0]; r.update(url=i['url'],host=host,http=code,source=src,last_checked=today,
        status='OK (opens)' if code==200 else r['status']); added.append(r); continue
    flags=['audio'] if re.search(r'audio only|sound only',i['note'],re.I) else []
    r=dict(date=i['date'],group=i['group'],meeting=i['meeting'],note='' if flags else i['note'],host=host,url=i['url'],source=src,
      flags=flags,http=code,status='OK (opens)' if code==200 else 'UNVERIFIED',last_checked=today)
    rows.append(r); added.append(r)
  json.dump(dict(pulled=live['fetched_at'],added=[(r['group'],r['date']) for r in added],
    dead=[dict(group=i['group'],date=i['date'],url=i['url']) for i in dead]),open(os.path.join(ROOT,'archive/club-videos-sync.json'),'w'),indent=1)
  print(f'R61: added/updated {len(added)}; dead (left out) {len(dead)}')
  for i in dead: print('  DEAD 404:',i['group'],i['date'],i['url'])
  return rows
LATEST=os.path.join(ROOT,'archive/archive-items.json')
def update_latest(rows):
  # R61: Latest videos (videos.html, built by build_archive.js) = newest working recording per group already listed there.
  d=json.load(open(LATEST)); items=d['sections']['videos']['items']
  lab={'Board Meeting':'board'}
  for s,l,_ in GROUPS: lab.setdefault(l,s)
  new=[]
  for it in items:
    g=lab.get(it['group']); rs=[r for r in rows if r['group']==g and r['link_status']=='ok' and 'drive.google' in r['host']]
    if g and rs:
      top=max(rs,key=lambda r:r['date'])
      if top['date']>it['date']: it=dict(group=it['group'],date=top['date'],url=top['url'])
    new.append(it)
  new.sort(key=lambda v:v['date'],reverse=True)
  # rewrite only the videos items block, keeping the file's hand-curated one-line-per-item layout
  sys.path.insert(0,os.path.dirname(os.path.abspath(__file__))); import archive_items as _aj  # R68: the one archive-items.json editor
  _aj.set_items(ROOT,'videos',new)
def main(args):
  rows=load(args)
  if '--offline' not in args and '--from-csv' not in args: rows=live_sync(rows)
  if '--check' in args:
    for r in rows:
      c=check(r['url'])
      if c is not None: r['http']=c
    r_checked=datetime.date.today().isoformat()
    for r in rows: r['last_checked']=r_checked
  for r in rows: r['link_status']=status_of(r)
  rows.sort(key=lambda r:(r['group'],r['date']),reverse=False)
  json.dump(rows,open(DATA,'w'),indent=1)
  if '--offline' not in args: update_latest(rows)
  by=collections.defaultdict(list)
  for r in rows: by[r['group']].append(r)
  # hub
  items=[]
  for s,l,_ in GROUPS:
    rs=by.get(s,[])
    if not rs: continue
    ds=sorted(r['date'] for r in rs)
    items.append(f'<div class="ph-row{" ph-alt" if len(items)%2 else ""}"><a class="ph-row-title" href="videos/{s}.html">{E(l)} Video Archives →</a> <span class="ph-row-meta">({rng(rs)})</span></div>')
  body=('<p class="ph-lead">Every Board and committee meeting recording we have, one list per group. '
        'For just the newest recording from each group, see <a href="videos.html">Latest Committee &amp; Board Meeting Videos</a>.</p>\n'
        '<div class="ph-hub">\n'+'\n'.join(items)+'\n</div>\n'
        '<nav class="ph-links"><a href="videos.html">Latest Committee &amp; Board Meeting Videos →</a><span class="ph-dot"> · </span><a href="did-you-know.html">How to watch (Did You Know) →</a></nav>')
  strip=[('All Archives →','main.html')]  # R44: one top link (Latest videos stays in the lower link row)
  open(os.path.join(ROOT,HUB),'w').write(_SR.assert_archive_top(page('Committee & Board Meeting Video Archives','pages/archive/meeting-videos.html',
     '<a href="main.html">All Archives →</a>',body,strip),HUB))  # STYLE-RULES R43/R44: 'Palm Hill Archives' link -> 'All Archives →'
  # group pages
  for s,l,_ in GROUPS:
    rs=sorted(by.get(s,[]),key=lambda r:r['date'],reverse=True)
    if not rs: continue
    out=[];month=None
    for i,r in enumerate(rs):
      m=datetime.date.fromisoformat(r['date']).strftime('%B %Y')  # STYLE-RULES.md: full months in headings
      if m!=month: out.append(f'<h2 class="ph-subhead">{m}</h2>'); month=m
      name=r['meeting'] or ('Board Meeting' if s=='board' else l+' Meeting')
      note=r['note']
      if note and note.lower() not in name.lower(): name=f'{name} — {note}' if not re.search(r'audio only|sound only',note,re.I) else name
      fl=[]
      if 'audio' in r['flags']: fl.append('<span class="ph-flag ph-flag-audio">🔊 Audio only</span>')
      st=r['link_status']
      if st=='broken': fl.append('<span class="ph-flag ph-flag-warn">Link not working (file moved or removed)</span>')
      elif st=='signin': fl.append('<span class="ph-flag ph-flag-note">Sign-in required (RPM SharePoint)</span>')
      elif st=='unverified': fl.append('<span class="ph-flag ph-flag-note">'+('YouTube' if 'youtu' in r['host'] else 'OneDrive')+' link, not yet checked</span>')
      if 'duplicate' in r['flags']: fl.append('<span class="ph-flag ph-flag-warn">Same link as another date</span>')
      if 'date-typo' in r['flags']: fl.append('<span class="ph-flag ph-flag-note">Club page shows “O9/29/2025”</span>')
      u=E(r['url'])
      out.append(f'<div class="ph-video{" ph-alt" if i%2 else ""}"><a class="ph-play" href="{u}" aria-label="Play the {E(name)} recording from {fdate(r["date"])}">▶</a><div><div class="ph-row-title"><a href="{u}">{E(name)}</a>{"".join(fl)}</div><div class="ph-row-meta">{fdate(r["date"])}</div></div></div>')
    body=(f'<p class="ph-row-meta" style="font-size:17px;margin-top:-6px"><b>{rng(rs)}</b></p>\n<p class="ph-lead">All {len(rs)} {E(l)} recordings we have, newest first. Tap a meeting to open it.</p>\n'+'\n'.join(out)+
      '\n<nav class="ph-links"><a href="../videos.html">Latest Committee &amp; Board Meeting Videos →</a></nav>')  # R43: one back link (strip)
    strip=[('All Archives →','../main.html')]  # R44: one top link (lower row keeps Latest videos)
    open(os.path.join(ROOT,f'pages/archive/videos/{s}.html'),'w').write(_SR.assert_archive_top(page(f'{l} Video Archives',f'pages/archive/videos/{s}.html',
      '<a href="../main.html">All Archives →</a>',body,strip),f'videos/{s}.html'))
  for s,l,_ in GROUPS: print(f'{l}: {len(by.get(s,[]))}')
  print('other:',len(by.get('other',[])),'total',len(rows))
  print('status:',collections.Counter(r['link_status'] for r in rows))
main(sys.argv)
